"""Play a database administrator who tries to change history, and show which check catches it.

Each scenario creates its own small ledger table (demo_<scenario>_<run id>), writes nine changes as
the application user, anchors, then tampers as the cluster master user and runs the auditor's
three checks on that table only. Run with --help.
"""
import datetime as dt
import json
import os
import sys

from ledger import audit
from ledger.context import Context, base_parser
from ledger.dataapi import SqlError

GUARD_OFF = "ALTER EVENT TRIGGER ledger_ddl_guard DISABLE"
GUARD_ON = "ALTER EVENT TRIGGER ledger_ddl_guard ENABLE ALWAYS"
HIST_OFF = "ALTER TABLE ledger.history DISABLE TRIGGER history_no_update_delete"
HIST_ON = "ALTER TABLE ledger.history ENABLE TRIGGER history_no_update_delete"
EDIT_FIRST = "UPDATE ledger.history SET doc = jsonb_set(doc, '{balance}', '999999') WHERE chain_id = '{c}' AND chain_seq = 1"
RECOMPUTE = """DO $$ DECLARE r ledger.history; p bytea := decode(repeat('00', 32), 'hex'); h bytea; BEGIN
  FOR r IN SELECT * FROM ledger.history WHERE chain_id = '{c}' ORDER BY chain_seq LOOP
    h := sha256(convert_to(ledger.canonical(r, r.chain_seq, p), 'UTF8'));
    UPDATE ledger.history SET prev_hash = p, row_hash = h WHERE id = r.id; p := h; END LOOP;
  UPDATE ledger.chain_head SET last_hash = p WHERE chain_id = '{c}'; END $$"""

# expect: "blocked" (the statement must fail), or the set of checks that must report a problem.
SCENARIOS = {
    "A": ("Direct UPDATE of a history row", [EDIT_FIRST], "blocked"),
    "B": ("Disable the DDL guard and the append-only trigger, edit a history row",
          [GUARD_OFF, HIST_OFF, EDIT_FIRST, HIST_ON, GUARD_ON], {"chain", "anchor"}),
    "C": ("As B, then recompute every hash and the chain head ('perfect' rewrite)",
          [GUARD_OFF, HIST_OFF, EDIT_FIRST, RECOMPUTE, HIST_ON, GUARD_ON], {"anchor"}),
    "D": ("Delete the last three history rows and rewind the chain head",
          [GUARD_OFF, HIST_OFF, "DELETE FROM ledger.history WHERE chain_id = '{c}' AND chain_seq > 6",
           "UPDATE ledger.chain_head SET last_seq = 6, last_hash = (SELECT row_hash FROM ledger.history "
           "WHERE chain_id = '{c}' AND chain_seq = 6) WHERE chain_id = '{c}'", HIST_ON, GUARD_ON], {"anchor", "reconcile"}),
    "E": ("Bypass the capture trigger with session_replication_role and change a balance",
          ["SET LOCAL session_replication_role = replica",
           "UPDATE ledger.{t} SET balance = 888888 WHERE id = 'A002'"], {"reconcile"}),
    "F": ("Disable the append-only trigger without turning off the DDL guard", [HIST_OFF], "blocked"),
    "G": ("Rename the primary key as the schema owner (what a migration tool would run)",
          ["SET LOCAL ROLE ledger_owner", "ALTER TABLE ledger.{t} RENAME COLUMN id TO account_id"], "blocked"),
}


def create_table(master, table):
    with master.transaction() as tx:
        for sql in ("SET LOCAL ROLE ledger_owner",
                    f"CREATE TABLE ledger.{table} (LIKE ledger.account INCLUDING ALL)",
                    f"CREATE TRIGGER {table}_ledger AFTER INSERT OR UPDATE OR DELETE ON ledger.{table} "
                    f"FOR EACH ROW EXECUTE FUNCTION ledger.capture_change('{table}')",
                    f"GRANT SELECT, INSERT, UPDATE, DELETE ON ledger.{table} TO app_user",
                    "RESET ROLE", f"SELECT (ledger_guard.register_table('ledger.{table}')).tbl_name"):
            master.query(sql, tx=tx)  # nosec B608 - table name is generated by this script


def write_changes(app, table):
    """Nine changes: five inserts, a two-row transfer, an attribute change, a delete."""
    for i in range(1, 6):
        app.query(f"INSERT INTO ledger.{table} (id, owner, balance) VALUES ('A00{i}', 'Customer {i}', {1000 * i})")  # nosec B608
    with app.transaction() as tx:
        app.query(f"UPDATE ledger.{table} SET balance = balance - 300 WHERE id = 'A001'", tx=tx)  # nosec B608
        app.query(f"UPDATE ledger.{table} SET balance = balance + 300 WHERE id = 'A002'", tx=tx)  # nosec B608
    app.query(f"""UPDATE ledger.{table} SET attrs = '{{"kyc": "verified"}}' WHERE id = 'A003'""")  # nosec B608
    app.query(f"DELETE FROM ledger.{table} WHERE id = 'A005'")  # nosec B608


def tamper(master, statements, table):
    try:
        with master.transaction() as tx:
            for sql in statements:
                master.query(sql.replace("{c}", table).replace("{t}", table), tx=tx)
        return None
    except SqlError as exc:
        return str(exc).split("\n")[0]


def detected_by(report, chain):
    c = report["chains"][chain]
    found = set()
    if not c["self_consistent"]:
        found.add("chain")
    if c["anchor_problems"]:
        found.add("anchor")
    if any(report["reconcile"].values()):
        found.add("reconcile")
    return found


def main():
    parser = base_parser(__doc__)
    parser.add_argument("--scenario", action="append", choices=sorted(SCENARIOS),
                        help="run only these scenarios (repeatable; default: all)")
    args = parser.parse_args()
    ctx = Context(args)
    master, app, auditor = ctx.db("master"), ctx.db("app_user"), ctx.db("auditor")
    s3, bucket = ctx.client("s3"), ctx.outputs()["AnchorBucket"]
    with open(ctx.public_key_path(), "rb") as f:
        pem = f.read()
    run_id = dt.datetime.now(dt.timezone.utc).strftime("%m%d%H%M%S")
    rows, failures = [], 0
    for key in args.scenario or sorted(SCENARIOS):
        title, statements, expect = SCENARIOS[key]
        table = f"demo_{key.lower()}_{run_id}"
        create_table(master, table)
        write_changes(app, table)
        ctx.invoke_anchor()
        error = tamper(master, statements, table)
        report = audit.run_checks(auditor, s3, bucket, pem, chains=[table], tables=[f"ledger.{table}"])
        found = detected_by(report, table)
        if expect == "blocked":
            ok = error is not None and not found
            outcome = f"blocked: {error}" if error else "NOT blocked"
        else:
            ok = error is None and found == expect
            outcome = f"detected by {sorted(found) or 'nothing'}" + (f" (statement failed: {error})" if error else "")
        failures += not ok
        print(f"[{'PASS' if ok else 'FAIL'}] {key}. {title}\n       -> {outcome}")
        rows.append({"scenario": key, "title": title, "table": table, "expected": sorted(expect) if isinstance(expect, set)
                     else expect, "error": error, "detected_by": sorted(found), "pass": ok, "report": report})
    path = os.path.join(args.results_dir, f"tamper-demo-{run_id}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(rows, f, indent=2, ensure_ascii=False)
    print(f"Details: {path}")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
